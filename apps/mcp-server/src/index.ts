import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";
import { spawn } from "node:child_process";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Keep track of the C++ simulator process
let simulatorProcess: ReturnType<typeof spawn> | null = null;
let telemetryLog: any[] = [];
let seqMs = 100;

function bootSimulator() {
  if (simulatorProcess) {
    return "Simulator is already running.";
  }
  
  const simBinary = join(__dirname, '../../../../build/dev/edge/sourcetrace_sim');
  simulatorProcess = spawn(simBinary, [], {
    shell: false,
    stdio: ['pipe', 'pipe', 'pipe']
  });

  createInterface({ input: simulatorProcess.stdout! }).on('line', (line) => {
    try {
      const data = JSON.parse(line);
      telemetryLog.unshift(data);
      if (telemetryLog.length > 50) telemetryLog.pop();
    } catch (e) {
      // ignore parse errors
    }
  });

  simulatorProcess.stderr!.on('data', () => {
    // Ignore stderr to not pollute MCP transport
  });

  simulatorProcess.on('exit', () => {
    simulatorProcess = null;
  });

  return "Simulator booted successfully.";
}

function sendCommand(request: any): string {
  if (!simulatorProcess) {
    return "Error: Simulator is not running. Boot it first.";
  }
  
  // Attach sequential monotonic timestamp
  request.atMs = seqMs++;
  simulatorProcess.stdin!.write(JSON.stringify(request) + '\n');
  return `Command sent: ${request.action}`;
}

// Create the MCP server
const server = new McpServer({
  name: "SourceTrace Edge Simulator",
  version: "1.0.0"
});

server.tool(
  "boot_simulator",
  "Starts the C++ edge terminal simulator process.",
  {},
  async () => {
    const result = bootSimulator();
    return {
      content: [{ type: "text", text: result }]
    };
  }
);

server.tool(
  "toggle_network",
  "Toggles the network connection state of the terminal.",
  { connected: z.boolean() },
  async ({ connected }) => {
    const result = sendCommand({ action: "network", connected });
    return {
      content: [{ type: "text", text: result }]
    };
  }
);

server.tool(
  "set_occupancy",
  "Simulates the IR occupancy sensor detecting a person.",
  { occupied: z.boolean() },
  async ({ occupied }) => {
    const result = sendCommand({ action: "occupancy", occupied });
    return {
      content: [{ type: "text", text: result }]
    };
  }
);

server.tool(
  "press_hardware_button",
  "Simulates a physical button press on the terminal device.",
  {},
  async () => {
    const result = sendCommand({ action: "button" });
    return {
      content: [{ type: "text", text: result }]
    };
  }
);

server.tool(
  "get_telemetry",
  "Retrieves the latest JSON state and telemetry events generated by the C++ engine.",
  {},
  async () => {
    return {
      content: [{ type: "text", text: JSON.stringify(telemetryLog, null, 2) }]
    };
  }
);

// Start receiving messages on stdin and sending on stdout
const transport = new StdioServerTransport();
server.connect(transport).catch(console.error);
